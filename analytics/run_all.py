from __future__ import annotations

import json
import math
from collections import Counter
from datetime import date, timedelta
from pathlib import Path

import numpy as np
import pandas as pd

import catalogue as C
import forecast_demand as F
import reference_data as R
import segment_supporters as SEG
import simulate as S

OUT = Path(__file__).resolve().parent.parent / "web" / "src" / "data"
OUT.mkdir(parents=True, exist_ok=True)
rng = np.random.default_rng(11)
FORECAST_DAYS = 56


def _clean(o):
    """Replace NaN/inf (invalid JSON) with None, recursively."""
    if isinstance(o, float) and not math.isfinite(o):
        return None
    if isinstance(o, dict):
        return {k: _clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_clean(v) for v in o]
    return o


def dump(name, obj):
    path = OUT / name
    path.write_text(json.dumps(_clean(obj), separators=(",", ":"), ensure_ascii=False, default=str, allow_nan=False))
    print(f"  wrote {path.name:<18} {path.stat().st_size / 1024:8.1f} KB")


def write_assumptions_md():
    lines = ["# Assumptions Register", "",
             "Generated by `analytics/run_all.py` from `analytics/catalogue.py`. Every figure is a placeholder until its owner confirms it.", "",
             "| ID | Area | Item | Value used | Owner | Confidence | Basis / action |", "|---|---|---|---|---|---|---|"]
    for a in C.ASSUMPTIONS:
        lines.append(f"| {a['id']} | {a['area']} | {a['item']} | {a['value']} | {a['owner']} | {a['confidence']} | {a['basis']} |")
    lines += ["", "## Real reference data", ""] + [f"- {x['id']}: [{x['name']}]({x['url']})" for x in R.SOURCES]
    p = Path(__file__).resolve().parent.parent / "docs" / "ASSUMPTIONS_REGISTER.md"
    p.write_text("\n".join(lines) + "\n")
    print(f"  wrote {p.name}")


def main():
    print("1/5 simulating daily visitation from real drivers …")
    daily = S.simulate_daily()
    hist = pd.DataFrame(daily)
    print(f"    total simulated visits: {hist.visitors.sum():,}")

    print("2/5 simulating supporters, bookings and giving …")
    W, course_runs, schools, venue = S.simulate_world(daily)
    print(f"    supporters: {len(W.supporters):,}  interactions: {sum(len(v) for v in W.inter.values()):,}")

    print("3/5 fitting demand model + backtest …")
    model, alpha = F.fit(hist)
    bt = F.backtest(hist)
    fc = F.forecast(model, alpha, S.DEMO_TODAY, FORECAST_DAYS, S.START)
    drivers = F.driver_effects(model)
    print(f"    alpha={alpha:.3f}  backtest MAE={bt['mae']}  MAPE={bt['mape']}%  naive MAE={bt['naiveDowMae']}")

    print("4/5 segmenting supporters …")
    seg = SEG.segment(W, S.DEMO_TODAY)
    seg_idx = seg.set_index("id")
    funnel = SEG.funnel(seg)
    cohorts = [c for c in SEG.cohort_conversion(W, seg) if c["cohort"] >= S.START.isoformat()[:7] and c["size"] >= 30]
    seg_summary = SEG.segment_summary(seg)

    print("5/5 writing JSON …")
    # ---- catalogue -------------------------------------------------------
    elements = []
    for e in C.ADOPT_ELEMENTS:
        adopted = W.adopted[e["id"]]
        if e["status"] == "restored":
            adopted = e["units"]
        elif e["status"] == "in_restoration":
            adopted = max(adopted, int(e["units"] * rng.uniform(.55, .85)))
        elements.append({**e, "adopted": int(min(adopted, e["units"]))})
    catalogue = dict(
        gstRate=C.GST_RATE, experiences=C.EXPERIENCES, events=C.EVENTS, courses=C.COURSES,
        schoolProgrammes=C.SCHOOL_PROGRAMMES, venuePackages=C.VENUE_PACKAGES, spaces=C.SPACES,
        membershipTiers=C.MEMBERSHIP_TIERS, funds=C.FUNDS, elements=elements,
        revenuePlan=C.REVENUE_PLAN_Y1, finance=C.FINANCE, marketing=C.MARKETING, assumptions=C.ASSUMPTIONS, sources=R.SOURCES,
        demoToday=S.DEMO_TODAY.isoformat(), simStart=S.START.isoformat(), simEnd=S.END.isoformat(),
    )
    dump("catalogue.json", catalogue)

    # ---- sessions for What's On (next 8 weeks) ----------------------------
    sessions = []
    for i, f in enumerate(fc):
        d = date.fromisoformat(f["date"])
        decay = max(.15, 1 - i / FORECAST_DAYS)
        exp_ = f["expected"]
        sessions.append(dict(id=f"grounds-{f['date']}", ref="grounds", date=f["date"], time="9:00–16:30",
                             capacity=600, booked=int(min(600, exp_ * .4 * decay))))
        if d.weekday() >= 2:
            for t in ("10:30", "13:30"):
                sessions.append(dict(id=f"house-tour-{f['date']}-{t}", ref="house-tour", date=f["date"], time=t,
                                     capacity=20, booked=int(min(20, rng.poisson(exp_ * .07 * decay)))))
        if d.weekday() >= 5:
            sessions.append(dict(id=f"garden-walk-{f['date']}", ref="garden-walk", date=f["date"], time="11:00",
                                 capacity=25, booked=int(min(25, rng.poisson(exp_ * .06 * decay)))))
        if d.weekday() == 5:
            ref = "taster-lime" if (d.isocalendar()[1] % 2) else "taster-stone"
            sessions.append(dict(id=f"{ref}-{f['date']}", ref=ref, date=f["date"], time="13:00",
                                 capacity=12, booked=int(min(12, rng.binomial(12, .5 * decay + .1)))))
    for ev in C.EVENTS:
        sessions.append(dict(id=ev["id"], ref=ev["id"], date=ev["date"], time=ev["time"], capacity=ev["capacity"],
                             booked=int(ev["capacity"] * rng.uniform(.25, .6))))
    for c in C.COURSES:
        for dt in c["dates"]:
            sessions.append(dict(id=f"{c['id']}-{dt}", ref=c["id"], date=dt, time="9:00–16:00",
                                 capacity=c["capacity"], booked=int(rng.integers(2, c["capacity"] - 1))))
    sessions.sort(key=lambda s: (s["date"], s["time"]))
    dump("sessions.json", sessions)

    # ---- supporters --------------------------------------------------------
    sup = []
    for s in W.supporters:
        r = seg_idx.loc[s["id"]]
        m = W.member.get(s["id"])
        sup.append(dict(**s, member=m, stage=r.stage, R=int(r.R), F=int(r.F), M=int(r.M), segment=r.segment,
                        recency=int(r.recency), value=round(float(r.monetary)),
                        lapseRisk=r.lapseRisk if isinstance(r.lapseRisk, str) else None,
                        interactions=sorted(W.inter.get(s["id"], []), key=lambda x: x[0])))
    dump("supporters.json", sup)

    # ---- venue calendar (upcoming confirmed + pipeline) -------------------
    upcoming = []
    for i in range(FORECAST_DAYS):
        d = S.DEMO_TODAY + timedelta(days=i)
        if d.weekday() == 5 and rng.random() < .6:
            upcoming.append(dict(date=d.isoformat(), space="Main House", kind="Wedding",
                                 title="Wedding (confirmed)", status="Confirmed"))
        if d.weekday() in (1, 2, 3) and not R.is_school_holiday(d) and rng.random() < .45:
            upcoming.append(dict(date=d.isoformat(), space="Stables Courtyard", kind="School group",
                                 title="School excursion (class booking)", status="Confirmed"))
        if d.weekday() in (2, 3) and rng.random() < .15:
            upcoming.append(dict(date=d.isoformat(), space="Main House", kind="Corporate",
                                 title="Corporate day (confirmed)", status="Confirmed"))
    for ev in C.EVENTS:
        upcoming.append(dict(date=ev["date"], space="Gardens & Lawn", kind="Public event", title=ev["name"], status="Confirmed"))
    stages = ["Enquiry", "Site visit", "Quote sent", "Deposit paid", "Confirmed"]
    pipeline = []
    for i in range(22):
        pk = C.VENUE_PACKAGES[rng.choice(len(C.VENUE_PACKAGES), p=[.45, .15, .2, .1, .1])]
        val = pk["peak_price"] if pk["unit"] == "venue fee" else pk["from_price"] * int(rng.integers(15, 40))
        pipeline.append(dict(id=f"L{i + 1:03d}", name=f"{S.FIRST[rng.integers(60)]} {S.LAST[rng.integers(50)]}",
                             package=pk["name"], kind=pk["kind"],
                             eventDate=(S.DEMO_TODAY + timedelta(days=int(rng.integers(30, 420)))).isoformat(),
                             enquired=(S.DEMO_TODAY - timedelta(days=int(rng.integers(1, 90)))).isoformat(),
                             stage=stages[rng.choice(5, p=[.35, .2, .2, .15, .1])], value=int(val)))

    # ---- KPIs and analytics bundle -----------------------------------------
    all_rows = [r for v in W.inter.values() for r in v]
    types = Counter(r[1] for r in all_rows)
    restoration_raised = sum(r[3] for r in all_rows
                             if (r[1] == "adoption") or (r[1] == "donation" and (r[4] or {}).get("fund") == "restoration"))
    kpis = dict(
        visits=int(hist.visitors.sum()), supporters=len(W.supporters),
        registeredVisits=types["visit"], paidBookings=sum(types[t] for t in SEG.PAID),
        members=int(seg.member.sum()),
        donors=int(seg.stage.isin(["Donor", "Repeat donor"]).sum()),
        restorationRaised=round(restoration_raised),
        totalGiving=round(sum(r[3] for r in all_rows if r[1] in SEG.GIFT)),
        unitsAdopted=int(sum(e["adopted"] for e in elements)),
        elementsRestored=sum(1 for e in elements if e["status"] == "restored"),
        elementsInRestoration=sum(1 for e in elements if e["status"] == "in_restoration"),
        schoolStudents=int(sum(s["students"] for s in schools)), schoolBookings=len(schools),
        courseLearners=int(sum(n for _, _, n in course_runs)), courseRuns=len(course_runs),
        volunteerHours=W.volunteer_hours, venueEvents=len(venue),
    )
    by_fund = Counter()
    for r in all_rows:
        if r[1] == "adoption":
            by_fund["Restoration Fund (Adopt-a-Stone)"] += r[3]
        elif r[1] == "donation":
            f = (r[4] or {}).get("fund", "general")
            by_fund[{"restoration": "Restoration Fund", "bursary": "Education Bursary Fund", "general": "Where it's needed most"}[f]] += r[3]
    giving_by_fund = [dict(fund=k, amount=round(v)) for k, v in by_fund.most_common()]
    analytics = dict(
        daily=[dict(date=r["date"], visitors=r["visitors"], rain=r["rain"], tmax=r["tmax"]) for r in daily],
        revenueByMonth=S.revenue_by_month(W), funnel=funnel, cohorts=cohorts, segments=seg_summary,
        forecast=fc, drivers=drivers, backtest=bt, alpha=round(alpha, 3), kpis=kpis,
        venueUpcoming=sorted(upcoming, key=lambda x: x["date"]), venuePipeline=pipeline,
        schoolsRecent=schools[-25:], givingByFund=giving_by_fund,
        monthlyVisitors=[dict(month=m, visitors=int(v)) for m, v in hist.assign(month=hist.date.str[:7]).groupby("month").visitors.sum().items()],
    )
    dump("analytics.json", analytics)
    dump("pathway.json", S.pathway_participants())
    write_assumptions_md()

    # quick sanity print
    rev = pd.DataFrame(analytics["revenueByMonth"]).drop(columns=["month", "gst"]).sum()
    print("\n  Year-1 simulated revenue by stream (GST incl.) vs plan:")
    for k, v in C.REVENUE_PLAN_Y1.items():
        print(f"    {k:<26} {rev.get(k, 0):>10,.0f}   plan {v:>10,.0f}")
    print(f"    {'TOTAL':<26} {rev.sum():>10,.0f}   plan {sum(C.REVENUE_PLAN_Y1.values()):>10,.0f}")
    print(f"\n  funnel: {[(f['stage'], f['reached']) for f in funnel]}")
    print(f"  KPIs: {kpis}")


if __name__ == "__main__":
    main()
